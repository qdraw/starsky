	/// <summary>
	///     Combines AppSettings.TrustedProxies with Cloudflare's IpRanges when
	///     AppSettings.TrustedProxiesCloudflare is true. Duplicates are removed.
	/// </summary>
	/// <param name="appSettings">source of TrustedProxies and TrustedProxiesCloudflare</param>
	/// <returns>the effective list of trusted proxy entries (IPs and/or CIDR ranges)</returns>
	public static List<string> GetTrustedProxies(AppSettings? appSettings)
	{
		var result = new List<string>();

		if ( appSettings?.TrustedProxies != null )
		{
			result.AddRange(appSettings.TrustedProxies);
		}

		if ( appSettings?.TrustedProxiesCloudflare == true )
		{
			result.AddRange(IpRanges);
		}

		return result.Distinct().ToList();
	}
}
